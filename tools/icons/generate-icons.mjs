import {mkdir, writeFile} from 'node:fs/promises';
import {join, resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {icons} from './icon-catalogue.mjs';

export function iconSvg(geometry) {
  return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">' +
    geometry + '</svg>\n';
}

export function iconStylesheet() {
  const entries = icons.map(([name]) => {
    return '  :where([data-icon="' + name + '"]) { --_uibms-icon-image: url("./svg/' + name + '.svg"); --_uibms-icon-content: ""; }';
  });
  return [
    '/* Generated by tools/icons/generate-icons.mjs. SVG files live beside this sheet in svg/. */',
    '@layer features {',
    '  @supports (mask: linear-gradient(black, black)) {',
    '    :where([data-icon]) {',
    '      --_uibms-icon-image: initial;',
    '      --_uibms-icon-content: none;',
    '    }',
    ...entries.map(entry => '  ' + entry),
    '    :where([data-icon])::before {',
    '      content: var(--_uibms-icon-content);',
    '      display: inline-block;',
    '      inline-size: var(--icon-size, 1em);',
    '      block-size: var(--icon-size, 1em);',
    '      flex: none;',
    '      vertical-align: middle;',
    '      background-color: currentColor;',
    '      mask: var(--_uibms-icon-image) center / contain no-repeat;',
    '      pointer-events: none;',
    '    }',
    '    :where([data-icon]:not(:empty))::before {',
    '      margin-inline-end: .35em;',
    '    }',
    '    @media (forced-colors: active) {',
    '      :where([data-icon])::before { forced-color-adjust: none; background-color: CanvasText; }',
    '    }',
    '  }',
    '}',
    ''
  ].join('\n');
}

async function main(folder = 'extensions/engines/icons') {
  const svgFolder = join(folder, 'svg');
  await mkdir(svgFolder, {recursive:true});
  await Promise.all([
    writeFile(join(folder,'icons.css'),iconStylesheet()),
    ...icons.map(([name,,geometry]) => writeFile(join(svgFolder,name+'.svg'),iconSvg(geometry)))
  ]);
  console.log('Generated ' + icons.length + ' SVG icons and icons.css in ' + folder);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main(process.argv[2]).catch(error => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
