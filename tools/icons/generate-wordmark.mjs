import {mkdir, writeFile} from 'node:fs/promises';
import {resolve, join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {glyphs} from './wordmark-glyphs.mjs';

const atlasSide = 8;
const frameCount = atlasSide ** 2;
const samples = 42;
const glyphAdvance = 102;
const inset = 28;
const height = 168;

function normalize(word) {
  if (typeof word !== 'string' || !/^[a-zA-Z -]+$/.test(word) || !/[a-zA-Z]/.test(word)) {
    throw new Error('Enter words using Latin letters A–Z, spaces, or hyphens.');
  }
  return word.trim().replace(/ +/g, ' ').toUpperCase();
}

function sample(stroke, origin) {
  const points = stroke.split(' ').map(pair => {
    const [x,y] = pair.split(',').map(Number);
    return [x + origin, y];
  });
  const cumulative = [0];
  for (let i = 1; i < points.length; i++) {
    const [x,y] = points[i];
    const [previousX,previousY] = points[i-1];
    cumulative.push(cumulative[i-1] + Math.hypot(x-previousX,y-previousY));
  }
  let segment = 1;
  return Array.from({length: samples}, (_, i) => {
    const distance = cumulative.at(-1) * i / (samples - 1);
    while (segment < points.length - 1 && cumulative[segment] < distance) segment++;
    const fraction = (distance - cumulative[segment-1]) / (cumulative[segment] - cumulative[segment-1]);
    return points[segment-1].map((value, axis) => value + (points[segment][axis]-value) * fraction);
  });
}

function layOut(word, columns) {
  const start = inset + (columns-word.length) * glyphAdvance / 2;
  return Array.from({length: columns}, (_, i) =>
    (glyphs[word[i]] ?? []).map(stroke => sample(stroke, start + i * glyphAdvance)));
}

function pairStrokes(from, to) {
  return from.flatMap((letter, index) => {
    const target = to[index];
    return Array.from({length: Math.max(letter.length,target.length)}, (_, i) => {
      const a = letter[i], b = target[i];
      // Fade a stroke as its points gather at the pen tip when a glyph
      // appears or disappears, including when the words have different lengths.
      return {from:a ?? b.map(() => b[0]), to:b ?? a.map(() => a.at(-1)),
        opacityFrom:Number(Boolean(a)), opacityTo:Number(Boolean(b)), index};
    });
  });
}

function smooth(value) {
  const t = Math.min(1, Math.max(0, value));
  return t*t*(3-2*t);
}

const number = value => Number(value.toFixed(1));
function frame(pairs, progress, columns) {
  return pairs.map(({from,to,opacityFrom,opacityTo,index}) => {
    const delay = .23 * index / Math.max(1,columns-1);
    const opacity = opacityFrom + (opacityTo-opacityFrom)*smooth((progress-delay)/.65);
    if (opacity === 0) return '';
    const points = from.map(([x,y], i) => {
      const along = i/(samples-1);
      const amount = smooth((progress-delay-.13*(1-along))/.64);
      const lift = Math.sin(Math.PI*amount);
      const [targetX,targetY] = to[i];
      const bend = 7*lift*Math.sin(2*Math.PI*along+index*.85);
      return number(x+(targetX-x)*amount+bend) + ',' + number(y+(targetY-y)*amount-11*lift*along);
    });
    const alpha = opacity === 1 ? '' : ' opacity="' + opacity.toFixed(3) + '"';
    return '<path d="M' + points.join(' ') + '"' + alpha + '/>';
  }).join('');
}

function stylesheet(name, width) {
  const selector = ':where([data-morph="' + name + '"])';
  const timeline = '--uibms-morph-' + name;
  const animation = 'uibms-morph-' + name;
  const size = atlasSide*100 + '%';
  const keys = Array.from({length:frameCount}, (_, i) => {
    const x = (i % atlasSide)/(atlasSide-1)*100;
    const y = Math.floor(i/atlasSide)/(atlasSide-1)*100;
    return '    ' + (i/(frameCount-1)*100).toFixed(6) + '% { mask-position: ' +
      x.toFixed(6) + '% ' + y.toFixed(6) + '%; }';
  });
  return [
    '/* Generated by tools/icons/generate-wordmark.mjs. */',
    '@layer features {',
    '  ' + selector + '::before {',
    '    content: "";',
    '    display: block;',
    '    inline-size: 100%;',
    '    aspect-ratio: ' + width + ' / ' + height + ';',
    '    background-color: currentColor;',
    '    mask: url("./' + name + '.svg") 0 0 / ' + size + ' ' + size + ' no-repeat;',
    '    pointer-events: none;',
    '  }',
    '  @media (forced-colors: active) {',
    '    ' + selector + '::before { background-color: CanvasText; }',
    '  }',
    '  @supports (animation-timeline: view(block)) and (animation-range: contain 0% contain 100%) {',
    '    @media (prefers-reduced-motion: no-preference) {',
    '      ' + selector + ' { view-timeline: ' + timeline + ' block; view-timeline-inset: 0; }',
    '      ' + selector + '::before {',
    '        animation: ' + animation + ' 1ms steps(1, end) both;',
    '        animation-timeline: ' + timeline + ';',
    '        animation-range: contain 0% contain 100%;',
    '      }',
    '      :where([data-effects="none"]) ' + selector + '::before,',
    '      ' + selector + ':where([data-effects="none"])::before { animation: none; }',
    '    }',
    '  }',
    '  @keyframes ' + animation + ' {',
    ...keys,
    '  }',
    '}',
    ''
  ].join('\n');
}

export function generateWordmark(start, end, preset) {
  const from = normalize(start), to = normalize(end);
  const name = preset ?? (from + '-to-' + to).toLowerCase().replace(/[ -]+/g,'-').replace(/^-+|-+$/g,'');
  if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name)) {
    throw new Error('Use a lowercase preset name with letters, digits, and single hyphens.');
  }
  const columns = Math.max(from.length,to.length);
  const width = inset*2 + columns*glyphAdvance;
  const pairs = pairStrokes(layOut(from,columns),layOut(to,columns));
  const atlasWidth = width*atlasSide, atlasHeight = height*atlasSide;
  const frames = Array.from({length:frameCount}, (_, i) => {
    const x = i % atlasSide * width;
    const y = Math.floor(i/atlasSide) * height;
    return '<g transform="translate(' + x + ' ' + y + ')">' + frame(pairs,i/(frameCount-1),columns) + '</g>';
  });
  const svg = [
    '<svg xmlns="http://www.w3.org/2000/svg" width="' + atlasWidth + '" height="' + atlasHeight +
      '" viewBox="0 0 ' + atlasWidth + ' ' + atlasHeight + '">',
    '<g fill="none" stroke="black" stroke-width="9" stroke-linecap="round" stroke-linejoin="round">',
    ...frames,
    '</g></svg>',
    ''
  ].join('\n');
  return {name, svg, css:stylesheet(name,width)};
}

async function main() {
  const [from,to,folder,preset,...extra] = process.argv.slice(2);
  if (!from || !to || !folder || extra.length) {
    throw new Error('Usage: node tools/icons/generate-wordmark.mjs "FIRST WORD" "SECOND WORD" output-directory [preset-name]');
  }
  const {name,svg,css} = generateWordmark(from,to,preset);
  await mkdir(folder,{recursive:true});
  await Promise.all([
    writeFile(join(folder,name+'.svg'),svg),
    writeFile(join(folder,name+'.css'),css)
  ]);
  console.log('Generated ' + name + '.svg and ' + name + '.css in ' + folder);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch(error => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
